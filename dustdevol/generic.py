def AGB_SN_yields(AGB_interp, SN_interp, iso_num):
    if iso_num is None:
        def inner(z, m):
            soln = fp_empty(m.shape[0])
            soln[m <= 8] = AGB_interp(z[m <= 8], m[m <= 8])
            soln[m > 8] = SN_interp(z[m > 8], m[m > 8])
            soln = soln * m
            return soln
    else:
        def inner(z, m):
            soln = fp_empty((m.shape[0], iso_num))
            soln[m <= 8] = AGB_interp(z[m <= 8], m[m <= 8])
            soln[m > 8] = SN_interp(z[m > 8], m[m > 8])
            soln = soln * m[:, None]
            return soln

    return inner


